//Используя цикл for вывести на экран:
//- горизонтальную линию из 10 восьмёрок
//- вертикальную линию из 10 восьмёрок.

public class Task06 {
    public static void main(String[] args) {
        for (int i = 10; i > 0; i--) { //выводим i 10 раз
            System.out.print(8);
        }
        for (int i = 10; i > 0; i--) {
            System.out.println(8);
        }
    }
}
